# Generates ref_svd.txt, the numpy SVD reference that check_svd.py compares
# --pheno-svd output against.  check_svd.py itself is pure Python, so CI does
# not need numpy; only regenerating the reference does.
#
# To regenerate (e.g. after changing the input generator in run_tests.sh):
#   ./run_tests.sh <plink2 dir>      # writes tmp_data.psam (and then fails the
#                                    # input-hash check if the inputs changed)
#   python3 make_ref.py tmp_data.psam > ref_svd.txt
#
# The committed ref_svd.txt was produced this way with numpy 2.4.6 (Python
# 3.14.6, macOS arm64).
#
# Both the raw and the column-centered phenotype matrices are decomposed, since
# check_svd.py accepts a match against either: only the layout of the result is
# under test here.
import hashlib
import sys

import numpy as np

psam_fn = sys.argv[1]
psam_sha256 = hashlib.sha256(open(psam_fn, "rb").read()).hexdigest()
psam = np.genfromtxt(psam_fn, comments=None, skip_header=1, usecols=(2, 3, 4))

print("# Generated by make_ref.py with numpy %s; see that file." % np.__version__)
print("input_sha256\t%s" % psam_sha256)
for name, mat in (("raw", psam), ("centered", psam - psam.mean(axis=0))):
    u, s, vh = np.linalg.svd(mat, full_matrices=False)
    for k in range(2):
        print("%s\ts\t%d\t%.17g" % (name, k, s[k]))
        print("%s\tvh\t%d\t%s" % (name, k, "\t".join("%.17g" % x for x in vh[k])))
        print("%s\tu\t%d\t%s" % (name, k, "\t".join("%.17g" % x for x in u[:, k])))
